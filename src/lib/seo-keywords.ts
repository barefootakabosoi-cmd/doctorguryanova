// Все ключевики одним списком (для генератора)
export const allKeywords = [
  ...highFrequencyKeywords,
  ...keywordClusters.flatMap((k) => [k.primary, ...k.secondary, ...k.longtail]),
];

// Получить кластер по ключевику
export function getClusterByKeyword(keyword: string): KeywordCluster | undefined {
  return keywordClusters.find(
    (k) =>
      k.primary === keyword ||
      k.secondary.includes(keyword) ||
      k.longtail.includes(keyword)
  );
}

// Получить случайный кластер (для генератора)
export function getRandomCluster(): KeywordCluster {
  return keywordClusters[Math.floor(Math.random() * keywordClusters.length)];
}

// Получить N случайных кластеров
export function getRandomClusters(n: number): KeywordCluster[] {
  const shuffled = [...keywordClusters].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, n);
}
